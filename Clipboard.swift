import AppKit
import Carbon.HIToolbox
import SwiftUI

@MainActor
@Observable
final class ClipboardHistory {
    enum Kind: Equatable { case text, link, color, image, files }

    struct Item: Identifiable {
        let id = UUID()
        let kind: Kind
        let text: String
        let image: NSImage?
        let imageData: Data?
        let imageType: NSPasteboard.PasteboardType?
        let files: [URL]
        let app: NSImage?
        let appName: String?
        let date = Date()
        let signature: Int
    }

    private(set) var items: [Item] = []
    private(set) var marked: [UUID] = []
    private(set) var dropping: Item?
    var selection = 0
    private(set) var isKeyboard = false

    var isOn: Bool {
        didSet {
            UserDefaults.standard.set(isOn, forKey: "clipboard")
            if !isOn { items.removeAll(); marked.removeAll() }
        }
    }
    var limit: Int {
        didSet {
            UserDefaults.standard.set(limit, forKey: "clipboardLimit")
            if items.count > limit { items.removeLast(items.count - limit) }
        }
    }
    var pastesOnPick: Bool {
        didSet { UserDefaults.standard.set(pastesOnPick, forKey: "clipboardPastes") }
    }
    var shortcutOn: Bool {
        didSet { UserDefaults.standard.set(shortcutOn, forKey: "clipboardShortcut"); registerHotKey() }
    }

    @ObservationIgnored var onCopied: ((Item) -> Void)?
    @ObservationIgnored var onHotKey: (() -> Void)?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var hotKey: EventHotKeyRef?
    @ObservationIgnored private static var shared: ClipboardHistory?

    static let maxLimit = 10
    private static let maxImageBytes = 8 << 20
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init() {
        let defaults = UserDefaults.standard
        defaults.register(defaults: ["clipboard": true, "clipboardLimit": Self.maxLimit, "clipboardPastes": true,
                                     "clipboardShortcut": true])
        isOn = defaults.bool(forKey: "clipboard")
        limit = min(max(defaults.integer(forKey: "clipboardLimit"), 3), Self.maxLimit)
        pastesOnPick = defaults.bool(forKey: "clipboardPastes")
        shortcutOn = defaults.bool(forKey: "clipboardShortcut")
        Self.shared = self
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor in ClipboardHistory.shared?.poll() }
        }
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
            Task { @MainActor in ClipboardHistory.shared?.onHotKey?() }
            return noErr
        }, 1, &spec, nil, nil)
        registerHotKey()
    }

    private func registerHotKey() {
        if let hotKey { UnregisterEventHotKey(hotKey) }
        hotKey = nil
        guard shortcutOn else { return }
        let id = EventHotKeyID(signature: OSType(0x4E434C50), id: 1)
        RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | controlKey), id, GetApplicationEventTarget(), 0, &hotKey)
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard isOn, let types = board.types, !types.contains(where: { Self.skipped.contains($0.rawValue) }) else { return }
        guard let item = read(board) else { return }
        insert(item)
        onCopied?(item)
    }

    private func read(_ board: NSPasteboard) -> Item? {
        let front = NSWorkspace.shared.frontmostApplication
        let app = front?.icon.map { Self.thumbnail($0, side: 40) }, appName = front?.localizedName
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return Self.fileItem(urls, app: app, appName: appName)
        }
        if let string = board.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let kind: Kind
            if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), url.scheme?.hasPrefix("http") == true, url.host != nil {
                kind = .link
            } else if Self.color(from: trimmed) != nil {
                kind = .color
            } else {
                kind = .text
            }
            return Item(kind: kind, text: string, image: nil, imageData: nil, imageType: nil, files: [],
                        app: app, appName: appName, signature: string.hashValue)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            guard let data = board.data(forType: type), data.count <= Self.maxImageBytes, let image = NSImage(data: data) else { continue }
            return Item(kind: .image, text: "Image \(Int(image.size.width)) × \(Int(image.size.height))", image: Self.thumbnail(image, side: 128),
                        imageData: data, imageType: type, files: [], app: app, appName: appName, signature: data.hashValue)
        }
        return nil
    }

    private static func fileItem(_ urls: [URL], app: NSImage?, appName: String?) -> Item {
        Item(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: ", "), image: thumbnail(NSWorkspace.shared.icon(forFile: urls[0].path), side: 96),
             imageData: nil, imageType: nil, files: urls, app: app, appName: appName, signature: urls.hashValue)
    }

    func preview(_ board: NSPasteboard?) {
        dropping = board.flatMap(read)
    }

    func take(_ board: NSPasteboard) -> Bool {
        guard isOn, let items = board.pasteboardItems, !items.isEmpty else { return false }
        let copies = items.map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
        let general = NSPasteboard.general
        general.clearContents()
        general.writeObjects(copies)
        guard let dropped = dropping, dropped.files.count > 1 else {
            poll()
            return true
        }
        lastChange = general.changeCount
        for url in dropped.files.reversed() {
            insert(Self.fileItem([url], app: dropped.app, appName: dropped.appName))
        }
        onCopied?(self.items[0])
        return true
    }

    private func insert(_ item: Item) {
        withAnimation(.arrive) {
            items.removeAll { $0.signature == item.signature }
            items.insert(item, at: 0)
            if items.count > limit { items.removeLast(items.count - limit) }
        }
    }

    func copy(_ chosen: [Item]) {
        let board = NSPasteboard.general
        board.clearContents()
        if chosen.count == 1, let item = chosen.first {
            switch item.kind {
            case .files: board.writeObjects(item.files as [NSURL])
            case .image: if let data = item.imageData, let type = item.imageType { board.setData(data, forType: type) }
            case .text, .link, .color: board.setString(item.text, forType: .string)
            }
        } else if chosen.allSatisfy({ $0.kind == .files }) {
            board.writeObjects(chosen.flatMap(\.files) as [NSURL])
        } else {
            board.setString(chosen.filter { $0.kind != .image }.map(\.text).joined(separator: "\n"), forType: .string)
        }
        lastChange = board.changeCount
        marked.removeAll()
        withAnimation(.arrive) {
            items.removeAll { item in chosen.contains { $0.id == item.id } }
            items.insert(contentsOf: chosen, at: 0)
        }
    }

    var markedItems: [Item] {
        marked.compactMap { id in items.first { $0.id == id } }
    }

    func mark(_ item: Item) {
        if let index = marked.firstIndex(of: item.id) { marked.remove(at: index) } else { marked.append(item.id) }
    }

    func markAll() {
        marked = items.map(\.id)
    }

    func unmark() {
        marked.removeAll()
    }

    func remove(_ item: Item) {
        withAnimation(.arrive) {
            items.removeAll { $0.id == item.id }
            marked.removeAll { $0 == item.id }
            selection = min(selection, max(items.count - 1, 0))
        }
    }

    func clear() {
        withAnimation(.settle) {
            items.removeAll()
            marked.removeAll()
        }
    }

    func setKeyboard(_ on: Bool) {
        isKeyboard = on
        selection = 0
        marked.removeAll()
    }

    static func thumbnail(_ image: NSImage, side: CGFloat) -> NSImage {
        let scale = min(side / max(image.size.width, image.size.height, 1), 1)
        let width = max(1, Int(image.size.width * scale)), height = max(1, Int(image.size.height * scale))
        guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height, bitsPerSample: 8,
                                         samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                         bytesPerRow: 0, bitsPerPixel: 0) else { return image }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        NSGraphicsContext.current?.imageInterpolation = .high
        image.draw(in: NSRect(x: 0, y: 0, width: width, height: height))
        NSGraphicsContext.restoreGraphicsState()
        let small = NSImage(size: NSSize(width: CGFloat(width) / 2, height: CGFloat(height) / 2))
        small.addRepresentation(rep)
        return small
    }

    static func color(from text: String) -> Color? {
        guard text.count == 7 || text.count == 4, text.hasPrefix("#") else { return nil }
        var hex = String(text.dropFirst())
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard let value = UInt32(hex, radix: 16) else { return nil }
        return Color(red: Double((value >> 16) & 0xff) / 255, green: Double((value >> 8) & 0xff) / 255, blue: Double(value & 0xff) / 255)
    }
}

struct ClipboardDropZone: View {
    static let height: CGFloat = 40
    let item: ClipboardHistory.Item?

    var body: some View {
        HStack(spacing: 6) {
            if let image = item?.image {
                Image(nsImage: image)
                    .resizable()
                    .scaledToFit()
                    .frame(width: 16, height: 16)
                    .clipShape(RoundedRectangle(cornerRadius: 3))
            } else {
                Image(systemName: "tray.and.arrow.down.fill")
                    .font(.system(size: 12, weight: .semibold))
                    .foregroundStyle(Color(red: 0.45, green: 0.85, blue: 0.8))
                    .symbolEffect(.bounce.down, options: .repeat(.periodic(delay: 0.5)))
            }
            Text(title)
                .font(.system(size: 12, weight: .semibold))
                .foregroundStyle(.white.opacity(0.85))
                .lineLimit(1)
                .truncationMode(.middle)
        }
        .padding(.horizontal, 10)
        .frame(maxWidth: .infinity)
        .frame(height: 26)
        .background(RoundedRectangle(cornerRadius: 9).strokeBorder(.white.opacity(0.25), style: StrokeStyle(lineWidth: 1, dash: [4, 3])))
        .padding(.horizontal, 12)
    }

    private var title: String {
        guard let item, item.kind != .image else { return "Drop to copy" }
        if item.files.count > 1 { return "Drop \(item.files.count) files" }
        return item.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? item.text
    }
}

final class DropCatcherView: NSView {
    private let lab: LabState

    init(lab: LabState) {
        self.lab = lab
        super.init(frame: .zero)
        registerForDraggedTypes([.fileURL, .URL, .string, .png, .tiff])
    }

    required init?(coder: NSCoder) { fatalError("use init(lab:)") }

    override func draggingEntered(_ sender: NSDraggingInfo) -> NSDragOperation {
        guard lab.canDrop else { return [] }
        lab.clipboard.preview(sender.draggingPasteboard)
        lab.setDropTarget(true)
        return .copy
    }

    override func draggingUpdated(_ sender: NSDraggingInfo) -> NSDragOperation {
        lab.canDrop ? .copy : []
    }

    override func draggingExited(_ sender: NSDraggingInfo?) {
        lab.setDropTarget(false)
        lab.clipboard.preview(nil)
    }

    override func performDragOperation(_ sender: NSDraggingInfo) -> Bool {
        lab.setDropTarget(false)
        let taken = lab.clipboard.take(sender.draggingPasteboard)
        lab.clipboard.preview(nil)
        return taken
    }
}

final class KeyCatcher: NSPanel {
    var onKey: ((NSEvent) -> Void)?

    init() {
        super.init(contentRect: NSRect(x: 0, y: 0, width: 1, height: 1), styleMask: [.borderless, .nonactivatingPanel],
                   backing: .buffered, defer: true)
        alphaValue = 0
        level = .statusBar
        collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
    }

    override var canBecomeKey: Bool { true }
    override func keyDown(with event: NSEvent) { onKey?(event) }
}

struct ClipboardView: View {
    let history: ClipboardHistory
    let onPick: (ClipboardHistory.Item) -> Void
    @State private var hovered: UUID?

    private let columns = 5
    private let spacing: CGFloat = 6

    var body: some View {
        let items = history.items
        let focus = items.first { $0.id == hovered }
            ?? (history.isKeyboard && items.indices.contains(history.selection) ? items[history.selection] : items.first)
        VStack(spacing: 8) {
            GeometryReader { geo in
                let side = (geo.size.width - spacing * CGFloat(columns - 1)) / CGFloat(columns)
                LazyVGrid(columns: Array(repeating: GridItem(.fixed(side), spacing: spacing), count: columns), spacing: spacing) {
                    ForEach(Array(items.enumerated()), id: \.element.id) { index, item in
                        ClipTile(item: item,
                                 number: history.isKeyboard && index < 9 ? index + 1 : nil,
                                 mark: history.marked.firstIndex(of: item.id).map { $0 + 1 },
                                 isSelected: history.isKeyboard && index == history.selection,
                                 isHovered: hovered == item.id,
                                 onMark: { history.mark(item) },
                                 onDelete: { history.remove(item) })
                            .frame(width: side, height: 48)
                            .onHover { inside in
                                if inside { hovered = item.id } else if hovered == item.id { hovered = nil }
                            }
                            .onTapGesture {
                                if history.marked.isEmpty && NSEvent.modifierFlags.isDisjoint(with: [.command, .shift]) {
                                    onPick(item)
                                } else {
                                    history.mark(item)
                                }
                            }
                            .transition(.scale(scale: 0.6).combined(with: .opacity))
                    }
                }
            }
            .frame(height: 48 * 2 + spacing)
            if let focus {
                ClipCaption(item: focus, history: history) { onPick(focus) }
                    .id(focus.id)
                    .transition(.blurReplace)
            }
        }
        .animation(.hover, value: focus?.id)
    }
}

private struct ClipTile: View {
    let item: ClipboardHistory.Item
    let number: Int?
    let mark: Int?
    let isSelected: Bool
    let isHovered: Bool
    let onMark: () -> Void
    let onDelete: () -> Void

    var body: some View {
        Color.clear
            .overlay { content }
            .clipped()
            .background(RoundedRectangle(cornerRadius: 9).fill(.white.opacity(mark == nil ? 0.07 : 0.14)))
            .clipShape(RoundedRectangle(cornerRadius: 9))
            .overlay(RoundedRectangle(cornerRadius: 9)
                .strokeBorder(.white.opacity(isSelected || mark != nil ? 0.85 : isHovered ? 0.3 : 0), lineWidth: isSelected || mark != nil ? 1.5 : 1))
            .overlay(alignment: .topLeading) {
                if mark != nil || isHovered {
                    Button(action: onMark) {
                        Group {
                            if let mark {
                                Text("\(mark)").font(.system(size: 8.5, weight: .bold).monospacedDigit()).foregroundStyle(.black)
                            } else {
                                Image(systemName: "checkmark").font(.system(size: 7, weight: .bold)).foregroundStyle(.white)
                            }
                        }
                        .frame(width: 14, height: 14)
                        .background(Circle().fill(mark == nil ? Color(white: 0.25) : .white))
                    }
                    .buttonStyle(.plain)
                    .padding(3)
                    .transition(.scale(scale: 0.5).combined(with: .opacity))
                }
            }
            .overlay(alignment: .bottomTrailing) {
                if let number, mark == nil {
                    Text("\(number)")
                        .font(.system(size: 8.5, weight: .bold).monospacedDigit())
                        .foregroundStyle(.black)
                        .frame(width: 13, height: 13)
                        .background(Circle().fill(.white.opacity(0.9)))
                        .padding(4)
                        .transition(.scale(scale: 0.5).combined(with: .opacity))
                }
            }
            .overlay(alignment: .topTrailing) {
                if isHovered {
                    Button(action: onDelete) {
                        Image(systemName: "xmark")
                            .font(.system(size: 7, weight: .bold))
                            .foregroundStyle(.white)
                            .frame(width: 14, height: 14)
                            .background(Circle().fill(Color(white: 0.25)))
                    }
                    .buttonStyle(.plain)
                    .padding(3)
                    .transition(.scale(scale: 0.5).combined(with: .opacity))
                }
            }
            .scaleEffect(isHovered || isSelected || mark != nil ? 1.05 : 1)
            .animation(.lift, value: isHovered)
            .animation(.lift, value: isSelected)
            .animation(.lift, value: mark)
            .contentShape(Rectangle())
    }

    @ViewBuilder private var content: some View {
        switch item.kind {
        case .image:
            if let image = item.image {
                Image(nsImage: image).resizable().scaledToFill()
            }
        case .color:
            (ClipboardHistory.color(from: item.text.trimmingCharacters(in: .whitespacesAndNewlines)) ?? .clear)
        case .files:
            if let icon = item.image {
                Image(nsImage: icon).resizable().scaledToFit().padding(7)
            }
        case .link:
            VStack(spacing: 4) {
                Image(systemName: "link").font(.system(size: 11, weight: .semibold))
                Text(Self.domain(item.text))
                    .font(.system(size: 9, weight: .medium))
                    .lineLimit(1)
                    .truncationMode(.middle)
            }
            .foregroundStyle(.white.opacity(0.85))
            .padding(.horizontal, 6)
            .padding(.bottom, number == nil ? 0 : 8)
        case .text:
            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                .font(.system(size: 9.5, weight: .medium))
                .foregroundStyle(.white.opacity(0.85))
                .lineLimit(number == nil ? 3 : 2)
                .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                .padding(.horizontal, 7)
                .padding(.vertical, 6)
        }
    }
}

extension ClipTile {
    static func domain(_ text: String) -> String {
        guard let host = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines))?.host() else { return text }
        return host.hasPrefix("www.") ? String(host.dropFirst(4)) : host
    }
}

private struct ClipCaption: View {
    let item: ClipboardHistory.Item
    let history: ClipboardHistory
    let onPick: () -> Void

    var body: some View {
        HStack(spacing: 6) {
            if !history.marked.isEmpty {
                Text("\(history.marked.count) selected")
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundStyle(.white.opacity(0.8))
                Spacer(minLength: 4)
                Button(action: onPick) {
                    Text(history.pastesOnPick ? "Paste ⏎" : "Copy ⏎")
                        .font(.system(size: 10, weight: .semibold))
                        .foregroundStyle(.black)
                        .padding(.horizontal, 7)
                        .padding(.vertical, 1)
                        .background(Capsule().fill(.white.opacity(0.9)))
                }
                .buttonStyle(.plain)
                Button("Reset") { history.unmark() }
                    .buttonStyle(.plain)
                    .font(.system(size: 10, weight: .semibold))
                    .foregroundStyle(.white.opacity(0.5))
            } else {
                details
            }
        }
        .frame(height: 14)
    }

    @ViewBuilder private var details: some View {
        if let app = item.app {
            Image(nsImage: app).resizable().frame(width: 13, height: 13)
        }
        Text(item.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? item.text)
            .font(.system(size: 11, weight: .medium))
            .foregroundStyle(.white.opacity(0.8))
            .lineLimit(1)
            .truncationMode(.middle)
        Spacer(minLength: 4)
        TimelineView(.periodic(from: .now, by: 30)) { context in
            Text(Self.age(of: item.date, now: context.date))
                .font(.system(size: 10, weight: .medium).monospacedDigit())
                .foregroundStyle(.white.opacity(0.4))
        }
        if history.isKeyboard {
            Text("␣ select  ⏎ paste")
                .font(.system(size: 10, weight: .medium))
                .foregroundStyle(.white.opacity(0.4))
        } else {
            Button("Clear") { history.clear() }
                .buttonStyle(.plain)
                .font(.system(size: 10, weight: .semibold))
                .foregroundStyle(.white.opacity(0.5))
        }
    }

    static func age(of date: Date, now: Date) -> String {
        let seconds = Int(now.timeIntervalSince(date))
        if seconds < 60 { return "now" }
        if seconds < 3600 { return "\(seconds / 60)m" }
        if seconds < 86400 { return "\(seconds / 3600)h" }
        return "\(seconds / 86400)d"
    }
}
